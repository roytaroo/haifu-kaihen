def glyph(ch):
    rows = G[ch.upper()]
    w = len(rows[0])
    bold = ch != ' '
    out = []
    for r in rows:
        bits = [c == '1' for c in r] + [False]
        if bold: bits = [bits[i] or (i > 0 and bits[i - 1]) for i in range(w + 1)]
        else: bits = bits[:w]
        out.append(bits)
    return out
